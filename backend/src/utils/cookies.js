import { env } from "../config/env.js";
import { AUTH_COOKIE_NAMES, AUTH_PATH, ACCESS_COOKIE_MAX_AGE_MS } from "../constants/auth.constants.js";

function baseCookieOptions() {
  return {
    httpOnly: true,
    secure: env.COOKIE_SECURE,
    // The browser only talks to the API through the frontend origin, so these
    // cookies are first party. Lax blocks cross site requests from carrying them.
    sameSite: "lax",
    ...(env.COOKIE_DOMAIN ? { domain: env.COOKIE_DOMAIN } : {})
  };
}

// OAuth provider round-trips come back as top level GET navigations, which
// Lax cookies are sent on.
const oauthSameSite = "lax";

export function setAuthCookies(res, { accessToken, refreshToken }) {
  res.cookie(AUTH_COOKIE_NAMES.access, accessToken, {
    ...baseCookieOptions(),
    path: "/",
    maxAge: ACCESS_COOKIE_MAX_AGE_MS
  });
  if (refreshToken) {
    res.cookie(AUTH_COOKIE_NAMES.refresh, refreshToken, {
      ...baseCookieOptions(),
      path: AUTH_PATH,
      maxAge: env.SESSION_DAYS * 24 * 60 * 60 * 1000
    });
  }
}

export function clearAuthCookies(res) {
  const base = baseCookieOptions();
  res.clearCookie(AUTH_COOKIE_NAMES.access, { ...base, path: "/" });
  // Clean up the old refresh cookie from earlier deployments.
  res.clearCookie(AUTH_COOKIE_NAMES.refresh, { ...base, path: AUTH_PATH });
}

function base64Encode(value) {
  return Buffer.from(JSON.stringify(value), "utf8").toString("base64url");
}

function base64Decode(value) {
  try {
    return JSON.parse(Buffer.from(value, "base64url").toString("utf8"));
  } catch {
    return null;
  }
}

function oauthAttemptCookieName(provider, state) {
  // State is generated by randomBytes(32). Reject anything else before using it
  // in a cookie name, so callback input can never control arbitrary names.
  if (typeof state !== "string" || !/^[A-Za-z0-9_-]{32,80}$/.test(state)) return null;
  return `arcdraw_${provider}_oauth_${state}`;
}

function setOAuthAttemptCookie(res, provider, state, payload, callbackPath, maxAge) {
  const name = oauthAttemptCookieName(provider, state);
  if (!name) throw new Error("Invalid OAuth state");
  res.cookie(name, base64Encode(payload), {
    ...baseCookieOptions(),
    httpOnly: true,
    // OAuth returns from a different site. In production this cookie is
    // Secure + SameSite=None; local HTTP falls back to Lax.
    sameSite: oauthSameSite,
    path: callbackPath,
    maxAge
  });
}

function readOAuthAttemptCookie(req, provider, state, callbackPath) {
  const name = oauthAttemptCookieName(provider, state);
  if (name && req.cookies?.[name]) {
    return base64Decode(req.cookies[name]);
  }

  // Read the previous three-cookie format during a rolling deployment.
  if (provider === "google" && req.cookies?.[AUTH_COOKIE_NAMES.googleState]) {
    return {
      state: req.cookies[AUTH_COOKIE_NAMES.googleState],
      nonce: req.cookies[AUTH_COOKIE_NAMES.googleNonce],
      codeVerifier: req.cookies[AUTH_COOKIE_NAMES.googleCodeVerifier]
    };
  }
  if (provider === "github" && req.cookies?.[AUTH_COOKIE_NAMES.githubState]) {
    return {
      state: req.cookies[AUTH_COOKIE_NAMES.githubState],
      codeVerifier: req.cookies[AUTH_COOKIE_NAMES.githubCodeVerifier]
    };
  }
  return null;
}

function clearOAuthAttemptCookie(res, provider, state, callbackPath) {
  const base = baseCookieOptions();
  const name = oauthAttemptCookieName(provider, state);
  if (name) res.clearCookie(name, { ...base, sameSite: oauthSameSite, path: callbackPath });

  // Also expire legacy names so stale cookies from older builds cannot linger.
  const legacyNames = provider === "google"
    ? [AUTH_COOKIE_NAMES.googleState, AUTH_COOKIE_NAMES.googleNonce, AUTH_COOKIE_NAMES.googleCodeVerifier]
    : [AUTH_COOKIE_NAMES.githubState, AUTH_COOKIE_NAMES.githubCodeVerifier];
  for (const legacyName of legacyNames) {
    res.clearCookie(legacyName, { ...base, sameSite: oauthSameSite, path: callbackPath });
  }
}

const googleCallbackPath = `${AUTH_PATH}/google/callback`;
const githubCallbackPath = `${AUTH_PATH}/github/callback`;

export function setGoogleOAuthCookies(res, { state, nonce, codeVerifier, desktopRedirectUri = null }, maxAge) {
  setOAuthAttemptCookie(res, "google", state, { state, nonce, codeVerifier, desktopRedirectUri }, googleCallbackPath, maxAge);
}

export function getGoogleOAuthCookies(req) {
  return readOAuthAttemptCookie(req, "google", req.query?.state, googleCallbackPath);
}

export function clearGoogleOAuthCookies(res, state) {
  clearOAuthAttemptCookie(res, "google", state, googleCallbackPath);
}

export function setGitHubOAuthCookies(res, { state, codeVerifier, desktopRedirectUri = null }, maxAge) {
  setOAuthAttemptCookie(res, "github", state, { state, codeVerifier, desktopRedirectUri }, githubCallbackPath, maxAge);
}

export function getGitHubOAuthCookies(req) {
  return readOAuthAttemptCookie(req, "github", req.query?.state, githubCallbackPath);
}

export function clearGitHubOAuthCookies(res, state) {
  clearOAuthAttemptCookie(res, "github", state, githubCallbackPath);
}
